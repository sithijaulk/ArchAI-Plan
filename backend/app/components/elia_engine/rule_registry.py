from __future__ import annotations

from dataclasses import asdict, dataclass, field
from enum import Enum
from typing import Any, Sequence


class RuleClass(str, Enum):
    LEGAL = "L"
    ENGINEERING = "E"
    PLANNER = "P"
    DATA_QUALITY = "D"


class RuleCategory(str, Enum):
    GEOMETRIC_VALIDITY = "geometric_validity"
    ENVIRONMENTAL_SUITABILITY = "environmental_suitability"
    LEGAL_ASSESSMENT = "legal_assessment"
    ELEVATED_INSTALLATION = "elevated_installation"
    USER_PREFERENCE = "user_preference"


class RuleOutcome(str, Enum):
    PASS = "pass"
    FAIL = "fail"
    UNKNOWN = "unknown"
    NOT_APPLICABLE = "not_applicable"
    REVIEW_REQUIRED = "review_required"


class EnforcementConsequence(str, Enum):
    BLOCK_ACCEPTANCE = "block_acceptance"
    FLAG_REVIEW = "flag_review"
    INFO_ONLY = "info_only"


class VerificationStatus(str, Enum):
    VERIFIED = "verified"
    PENDING_ENACTMENT = "pending_enactment"
    ADVISORY_OVERSEAS = "advisory_overseas"
    UNVERIFIED = "unverified"


@dataclass(frozen=True)
class RuleDefinition:
    rule_id: str
    version: str
    rule_class: RuleClass
    category: RuleCategory
    title: str
    description: str
    applicable_targets: tuple[str, ...]
    applicability_conditions: str
    required_inputs: tuple[str, ...]
    evaluation_method: str
    numeric_value: float | None = None
    numeric_units: str | None = None
    source_reference: str | None = None
    geographic_scope: str | None = None
    verification_status: VerificationStatus = VerificationStatus.VERIFIED
    missing_data_behavior: str = "mark_unknown"
    enforcement_consequence: EnforcementConsequence = EnforcementConsequence.FLAG_REVIEW

    def to_dict(self) -> dict[str, Any]:
        data = asdict(self)
        data["rule_class"] = self.rule_class.value
        data["category"] = self.category.value
        data["verification_status"] = self.verification_status.value
        data["enforcement_consequence"] = self.enforcement_consequence.value
        return data


@dataclass
class RuleEvaluationResult:
    rule_id: str
    version: str
    rule_class: str
    category: str
    title: str
    applicability: str  # "applicable", "not_applicable", "unknown"
    outcome: str  # "pass", "fail", "unknown", "not_applicable", "review_required"
    affected_object_ids: list[str] = field(default_factory=list)
    measured_value: Any | None = None
    measured_units: str | None = None
    evidence: str = ""
    missing_inputs: list[str] = field(default_factory=list)
    explanation: str = ""
    practical_remedy: str | None = None
    evaluation_time: str = ""
    upstream_revision: int | None = None

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


